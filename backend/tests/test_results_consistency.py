# ── v9 improvement round ──────────────────────────────────────────────────────

v9 = pytest.mark.skipif(not (VR.V9_DIR / "stage_final.json").exists(), reason="v9 results not present")


@v9
def test_v9_split_is_frozen_and_disjoint():
    sp = _j(VR.V9_DIR / "split.json")
    assert sp["seed"] == 2026 and sp["n_dev"] == 150 and sp["n_test"] == 37
    assert not set(sp["dev_people"]) & set(sp["test_people"])
    c = sp["checks"]
    assert c["no_person_in_both"] and c["ohio_excluded"] and c["duplicate_segment_step_rows"] == 0


@v9
def test_v9_thresholds_come_from_dev_and_promotion_rule_holds():
    pol, fin = _j(VR.V9_DIR / "stage_policy.json"), _j(VR.V9_DIR / "stage_final.json")
    assert pol["population"].startswith("DEV")
    cand = f"candidate: {fin['selected']}"
    assert fin["thresholds_from_dev"][cand]["policy"] == pol["models"][fin["selected"]]["chosen"]["threshold"]
    vs = fin["test_candidate_vs_baseline"]
    assert vs["roc_auc_diff_mean"] > 0 and vs["roc_auc_diff_ci95"][0] > -0.002 and vs["accuracy_diff_ci95"][0] >= -0.005
    b = fin["results"]["baseline (v7 config, DEV-trained)"]["test"]
    assert b["alerts_chosen_policy"]["serious_warned"] > b["alerts_v7_policy"]["serious_warned"]
    assert b["alerts_chosen_policy"]["false_alerts_per_patient_day"] <= b["alerts_v7_policy"]["false_alerts_per_patient_day"]


@v9
def test_v9_verified_and_quoted():
    ver = _j(VR.INV / "verified_metrics.json")
    names = [c["check"] for c in ver["checks"]]
    assert any(n.startswith("v9 TEST") for n in names) and any(n.startswith("README v9") for n in names)
    assert ver["checks_failed"] == 0
