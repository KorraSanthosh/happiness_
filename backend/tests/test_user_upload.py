def _times(hours, step_min=5, start="2024-05-01 06:00"):
    return pd.date_range(start, periods=int(hours * 60 / step_min), freq=f"{step_min}min")


def _wave(n):
    return 140 + 50 * np.sin(np.arange(n) / 20)


def dexcom_csv(hours=30):
    t = _times(hours)
    rows = ["Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Glucose Value (mg/dL),Insulin Value (u),Carb Value (grams)"]
    rows += [f"{i},{ts:%Y-%m-%dT%H:%M:%S},EGV,,{g:.0f},," for i, (ts, g) in enumerate(zip(t, _wave(len(t))))]
    rows.append(f"9999,{t[30]:%Y-%m-%dT%H:%M:%S},Carbs,,,,45")
    rows.append(f"9998,{t[31]:%Y-%m-%dT%H:%M:%S},Insulin,Fast-Acting,,4,")
    rows.append(f"9997,{t[40]:%Y-%m-%dT%H:%M:%S},EGV,,High,,")
    return "\n".join(rows).encode()


def libre_mmol_csv(hours=30):
    t = _times(hours, 15, "2024-05-13 06:00")                  # day 13 > 12: only day-first parses
    rows = ["Glucose Data,Generated on,13-06-2024 10:00 UTC,Generated by,Someone",
            "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L,Rapid-Acting Insulin (units),Carbohydrates (grams)"]
    rows += [f"FreeStyle LibreLink,X,{ts:%d-%m-%Y %H:%M},0,{g / 18.018:.1f},,," for ts, g in zip(t, _wave(len(t)))]
    return "\n".join(rows).encode()


def generic_csv(hours=30):
    t = _times(hours)
    return pd.DataFrame({"time": t.strftime("%Y-%m-%d %H:%M"), "glucose": _wave(len(t)).round()}).to_csv(index=False).encode()


def test_dexcom_export_parses_glucose_events_and_skips_high_low():
    grid, s = U.parse_cgm_csv(dexcom_csv())
    assert s["format"] == "Dexcom Clarity export" and s["units"] == "mg/dL" and s["reading_interval_min"] == 5
    assert grid.carbs.sum() == 45 and grid.insulin.sum() == 4
    assert any("High" in n for n in s["notes"])
    assert 39 <= grid.glucose.min() and grid.glucose.max() <= 450


def test_libreview_mmol_day_first_export():
    grid, s = U.parse_cgm_csv(libre_mmol_csv())
    assert s["format"] == "FreeStyle LibreView export" and s["units"].startswith("mmol")
    assert s["reading_interval_min"] == 15 and 120 < grid.glucose.mean() < 160
    assert s["last"].startswith("2024-05-14")                 # 13-05 parsed as 13 May, not an error


def test_generic_csv_and_short_or_bad_files():
    grid, s = U.parse_cgm_csv(generic_csv())
    assert s["format"] == "generic CSV" and s["hours"] >= 29 and not s["has_carbs"]
    with pytest.raises(U.UploadError, match="at least 6 hours"):
        U.parse_cgm_csv(generic_csv(hours=3))
    with pytest.raises(U.UploadError, match="time column"):
        U.parse_cgm_csv(b"a,b\n1,2\n")


needs_pack = pytest.mark.skipif(not (twin_v7.PACK_DIR / "streams.parquet").exists(), reason="demo pack not built")


@needs_pack
def test_upload_creates_a_twin_that_predicts_and_can_be_deleted():
    files = {"file": ("mine.csv", dexcom_csv(), "text/csv")}
    assert client.post("/api/v7/upload", files=files, data={"diabetes_type": "T2D"}).status_code == 422   # no consent
    r = client.post("/api/v7/upload", files=files, data={"diabetes_type": "T2D", "age": "54", "hba1c": "7.8",
                                                         "on_metformin": "true", "consent": "true"})
    assert r.status_code == 200, r.text
    pid = r.json()["patient_id"]
    assert pid in [p["patient_id"] for p in client.get("/api/v7/patients").json()["patients"]]
    d = client.get(f"/api/v7/patients/{pid}").json()
    assert d["uploaded"] and d["ehr"]["available"] and "Metformin" in d["ehr"]["conditions_and_drugs"]
    p = client.post(f"/api/v7/predict/{pid}", params={"bin": d["default_bin"]}).json()
    assert set(p["horizons"]) == {"30m", "60m", "2h"} and all(0 <= h["probability"] <= 1 for h in p["horizons"].values())
    assert client.delete(f"/api/v7/upload/{pid}").status_code == 200
    assert client.get(f"/api/v7/patients/{pid}").status_code == 404
    assert client.delete("/api/v7/upload/hupa_0001").status_code == 404                                  # demo data cannot be deleted


@needs_pack
def test_example_file_round_trips():
    ex = client.get("/api/v7/upload/example.csv")
